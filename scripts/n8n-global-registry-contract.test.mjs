import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const schema = read("../supabase/migrations/20261020120000_n8n_global_whatsapp_registry.sql");
const lifecycle = read("../supabase/migrations/20261020123000_n8n_global_job_registration_rpc.sql");
const history = read("../supabase/migrations/20261020130000_n8n_cfcf_job_history_rpc.sql");
const contract = read("../docs/n8n-global-whatsapp-worker-contract.md");
const campaign = read("../src/features/cfcf/services/contact-groups.service.ts");
const workspace = read("../src/features/cfcf/services/workspace-automation.service.ts");
const campaignUi = read("../src/features/cfcf/pages/ContactGroupsPanel.tsx");
const workspaceUi = read("../src/features/cfcf/pages/WorkspacePage.tsx");

test("registry uses sequential integer identity primary keys", () => {
  for (const column of [
    "n8n_global_job_id",
    "n8n_whatsapp_communication_id",
    "n8n_whatsapp_delivery_id",
  ]) {
    assert.match(schema, new RegExp(column + " integer generated by default as identity \\(start with 100 increment by 1\\) primary key"));
  }
  assert.doesNotMatch(schema, /uuid\s+primary key/i);
});

test("registry migrations remain separate from PWA push tables", () => {
  for (const table of ["clearflow_push_subscriptions", "clearflow_push_outbox", "clearflow_push_alert_state"]) {
    assert.equal(schema.includes(table), false, "registry migration must not reference " + table);
    assert.equal(lifecycle.includes(table), false, "lifecycle migration must not reference " + table);
  }
});

test("registry tables are not directly granted to browser roles", () => {
  assert.match(schema, /revoke all on table public\.n8n_global_jobs from anon, authenticated/i);
  assert.match(schema, /revoke all on table public\.n8n_whatsapp_communications from anon, authenticated/i);
  assert.match(schema, /revoke all on table public\.n8n_whatsapp_deliveries from anon, authenticated/i);
  assert.match(lifecycle, /grant execute on function public\.n8n_claim_global_jobs\(integer\) to service_role/i);
  assert.match(lifecycle, /grant execute on function public\.n8n_record_whatsapp_delivery_result\(integer,text,text,text,text,text\) to service_role/i);
  assert.match(lifecycle, /grant execute on function public\.n8n_finish_global_job\(integer,text,text\) to service_role/i);
});

test("authenticated campaign registration proves group ownership server-side", () => {
  assert.match(lifecycle, /elsif p_job_type = 'manual_campaign' then/);
  assert.match(lifecycle, /count\(distinct btrim\(requested\.group_id\)\)/);
  assert.match(lifecycle, /g\.product_id = 'CFCF'/);
  assert.match(lifecycle, /g\.tenant_id = p_tenant_id/);
  assert.match(lifecycle, /g\.person_id = p_person_id/);
  assert.match(lifecycle, /Every campaign Contact Group must belong to the authorized CFCF tenant owner/);
});

test("CFCF job types must match their communication types at the RPC boundary", () => {
  assert.match(lifecycle, /p_communication_type is null[\\s\\S]*?Unsupported WhatsApp communication type/);
  assert.match(lifecycle, /p_job_type = 'manual_campaign' and p_communication_type <> 'campaign'/);
  assert.match(lifecycle, /p_job_type = 'pending_reminder' and p_communication_type <> 'pending_reminder'/);
  assert.match(lifecycle, /p_job_type = 'report' and p_communication_type <> 'report'/);
  assert.match(lifecycle, /CFCF job type does not match WhatsApp communication type/);
});

test("Pending and Report retain the per-Fund hourly guard", () => {
  assert.match(lifecycle, /pg_advisory_xact_lock\(\s*hashtext\(p_tenant_id\),\s*hashtext\(p_source_record_id \|\| ':' \|\| p_job_type\)/);
  assert.match(lifecycle, /limited to once per hour for this Fund/);
});

test("stale claims time out without requeue", () => {
  assert.match(lifecycle, /set status = 'timed_out'[\s\S]*?where status = 'picked_up'[\s\S]*?picked_up_at < now\(\) - interval '90 minutes'/);
  assert.match(contract, /no automatic requeue/i);
});

test("completion cannot leave queued deliveries behind", () => {
  assert.match(lifecycle, /Cannot complete a global job while recipient deliveries remain queued/);
  assert.match(lifecycle, /d\.status = 'queued'/);
});

test("uncertain delivery is not automatically resent", () => {
  assert.match(lifecycle, /v_current_status = 'uncertain' and p_status = 'sent_to_server'/);
  assert.match(contract, /No automatic send retries, no automatic requeue, and no blind resend/);
});

test("history RPC is authenticated and bounded", () => {
  assert.match(history, /p_limit < 1 or p_limit > 100/);
  assert.match(history, /a\.access_type = 'tenantowner'/);
  assert.match(history, /grant execute on function public\.n8n_list_cfcf_whatsapp_jobs\(text, integer\) to authenticated/i);
});

test("Launch Campaign and bulk actions register through the global RPC", () => {
  assert.match(campaign, /rpc\("n8n_register_whatsapp_job"/);
  assert.match(workspace, /rpc\("n8n_register_whatsapp_job"/);
  assert.doesNotMatch(campaign, /functions\.invoke\(["']campaign-dispatch/);
});

test("send UI gates remain disabled", () => {
  assert.match(campaignUi, /CAMPAIGN_AUTOMATION_ENABLED\s*=\s*false/);
  assert.match(workspaceUi, /CFCF_GLOBAL_WHATSAPP_REGISTRATION_ENABLED\s*=\s*false/);
});

test("contract forbids PWA changes and activation before runtime validation", () => {
  assert.match(contract, /Do not modify PWA push-notification tables/);
  assert.match(contract, /Do not activate or enable UI gates/);
});

test("worker contract requires randomized waits and sequential queue processing", () => {
  assert.ok(contract.includes("native n8n **Wait** node"));
  assert.match(contract, /15 seconds, 30 seconds, or 60 seconds/);
  assert.match(contract, /Process claimed jobs and their queued deliveries sequentially/);
  assert.match(contract, /one sender execution at a time/);
  assert.match(contract, /do not connect an error branch back to the sender/);
  assert.match(contract, /A timeout or ambiguous provider result is recorded as `uncertain`/);
  assert.match(contract, /A non-queued delivery is skipped before the wait\/send path/);
});

test("global queue claim is bounded, serialized, and never reclaims picked-up jobs", () => {
  assert.match(lifecycle, /create or replace function public\.n8n_claim_global_jobs\(p_limit integer default 25\)/);
  assert.match(lifecycle, /p_limit < 1 or p_limit > 100/);
  assert.match(lifecycle, /where j\.status = 'registered'[\s\S]*?for update skip locked[\s\S]*?limit p_limit/);
  assert.match(lifecycle, /where status = 'picked_up'[\s\S]*?picked_up_at < now\(\) - interval '90 minutes'/);
  assert.doesNotMatch(lifecycle, /set status = 'registered'[\s\S]{0,500}where status = 'timed_out'/);
});

test("terminal delivery states cannot return to queued", () => {
  assert.match(lifecycle, /v_current_status <> 'queued'[\s\S]*?not \(v_current_status = 'uncertain' and p_status = 'sent_to_server'\)/);
  assert.match(lifecycle, /p_status not in \('sent_to_server', 'failed', 'uncertain', 'skipped'\)/);
  assert.match(lifecycle, /Cannot complete a global job while recipient deliveries remain queued/);
});
