-- Create Cycle rows for any legacy billing/payout/commission cycle not yet represented.
WITH legacy_cycles AS (
  SELECT s.product_id, s.tenant_id, s.fund_id, (e.key)::integer AS cycle_number
  FROM public.cfcf_shares s
  CROSS JOIN LATERAL jsonb_each(COALESCE(s.billing_entries, '{}'::jsonb)) e
  WHERE e.key ~ '^[1-9][0-9]*$' AND e.key::numeric <= 2147483647
  UNION
  SELECT f.product_id, f.tenant_id, f.fund_id, a.ordinality::integer
  FROM public.cfcf_funds f
  CROSS JOIN LATERAL jsonb_array_elements(COALESCE(f.cycle_payout_amounts, '[]'::jsonb))
    WITH ORDINALITY AS a(value, ordinality)
  WHERE a.value <> 'null'::jsonb
  UNION
  SELECT f.product_id, f.tenant_id, f.fund_id, a.ordinality::integer
  FROM public.cfcf_funds f
  CROSS JOIN LATERAL jsonb_array_elements(COALESCE(f.cycle_commissions, '[]'::jsonb))
    WITH ORDINALITY AS a(value, ordinality)
  WHERE a.value <> 'null'::jsonb
  UNION
  SELECT s.product_id, s.tenant_id, s.fund_id, s.payout_cycle_number
  FROM public.cfcf_shares s WHERE s.payout_cycle_number IS NOT NULL AND s.payout_cycle_number > 0
)
INSERT INTO public.cfcf_cycles(product_id, tenant_id, fund_id, cycle_number)
SELECT DISTINCT lc.product_id, lc.tenant_id, lc.fund_id, lc.cycle_number
FROM legacy_cycles lc
WHERE lc.cycle_number > 0
ON CONFLICT (fund_id, cycle_number) DO NOTHING;

-- Copy the legacy per-Cycle arrays into their authoritative Cycle columns.
UPDATE public.cfcf_cycles c
SET planned_payout_amount = COALESCE(
      c.planned_payout_amount,
      CASE WHEN jsonb_typeof(f.cycle_payout_amounts -> (c.cycle_number - 1)) = 'number'
           AND (f.cycle_payout_amounts ->> (c.cycle_number - 1)) ~ '^[0-9]+$'
           THEN (f.cycle_payout_amounts ->> (c.cycle_number - 1))::integer END
    ),
    commission_amount = COALESCE(
      c.commission_amount,
      CASE WHEN jsonb_typeof(f.cycle_commissions -> (c.cycle_number - 1)) = 'number'
           AND (f.cycle_commissions ->> (c.cycle_number - 1)) ~ '^[0-9]+$'
           THEN (f.cycle_commissions ->> (c.cycle_number - 1))::integer END
    ),
    updated_at = now()
FROM public.cfcf_funds f
WHERE f.fund_id = c.fund_id AND f.tenant_id = c.tenant_id AND f.product_id = c.product_id;

-- Migrate each JSONB bill to one relational row. Unknown historical dates remain NULL.
INSERT INTO public.cfcf_bills(product_id, tenant_id, fund_id, cycle_id, share_id, amount, bill_date)
SELECT s.product_id, s.tenant_id, s.fund_id, c.cycle_id, s.share_id,
       (e.value #>> '{}')::integer,
       CASE WHEN d.value ~ '^\\d{4}-\\d{2}-\\d{2}$' THEN d.value::date ELSE NULL END
FROM public.cfcf_shares s
CROSS JOIN LATERAL jsonb_each(COALESCE(s.billing_entries, '{}'::jsonb)) e
JOIN public.cfcf_cycles c
  ON c.product_id = s.product_id AND c.tenant_id = s.tenant_id
 AND c.fund_id = s.fund_id AND c.cycle_number = e.key::integer
LEFT JOIN LATERAL (SELECT s.billing_entry_dates ->> e.key AS value) d ON true
WHERE e.key ~ '^[1-9][0-9]*$'
  AND jsonb_typeof(e.value) = 'number'
  AND (e.value #>> '{}') ~ '^[0-9]+$'
  AND (e.value #>> '{}')::numeric <= 2147483647
ON CONFLICT (tenant_id, fund_id, cycle_id, share_id) DO NOTHING;

-- A log record is created in the same transaction as each successful data change.
CREATE OR REPLACE FUNCTION public.cfcf_log_manager_action()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_row jsonb;
  v_old jsonb;
  v_tenant_id text;
  v_product_id text;
  v_entity_id text;
  v_entity_type text;
  v_actor_person_id text;
  v_action text;
BEGIN
  v_row := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  v_old := CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) ELSE NULL END;
  v_tenant_id := v_row ->> 'tenant_id';
  v_product_id := COALESCE(v_row ->> 'product_id', 'CFCF');
  IF v_tenant_id IS NULL OR v_product_id <> 'CFCF' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  v_entity_type := CASE TG_TABLE_NAME
    WHEN 'cfcf_funds' THEN 'fund'
    WHEN 'cfcf_cycles' THEN 'cycle'
    WHEN 'cfcf_bills' THEN 'bill'
    WHEN 'cfcf_shares' THEN 'share'
    WHEN 'cfcf_payments' THEN 'payment'
    WHEN 'cfcf_fund_other_entries' THEN 'fund_adjustment'
    WHEN 'contacts' THEN 'contact'
    ELSE TG_TABLE_NAME
  END;
  v_entity_id := COALESCE(v_row ->> 'fund_id', v_row ->> 'cycle_id', v_row ->> 'bill_id',
    v_row ->> 'share_id', v_row ->> 'payment_id', v_row ->> 'entry_id', v_row ->> 'contact_id');
  v_action := lower(v_entity_type || '_' || TG_OP);
  SELECT p.person_id INTO v_actor_person_id
  FROM public.persons p
  WHERE p.tenant_id = v_tenant_id AND p.product_id = v_product_id
    AND lower(p.email) = lower(COALESCE(auth.jwt() ->> 'email', ''))
  ORDER BY (p.status = 'active') DESC, p.person_id
  LIMIT 1;
  INSERT INTO public.cfcf_activity_log(
    product_id, tenant_id, actor_person_id, action_type, entity_type, entity_id,
    description, before_data, after_data
  ) VALUES (
    v_product_id, v_tenant_id, v_actor_person_id, v_action, v_entity_type, v_entity_id,
    initcap(replace(v_entity_type, '_', ' ')) || ' ' || lower(TG_OP),
    v_old, CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE v_row END
  );
  DELETE FROM public.cfcf_activity_log a
  WHERE a.tenant_id = v_tenant_id AND a.product_id = v_product_id
    AND a.action_id NOT IN (
      SELECT keep.action_id FROM public.cfcf_activity_log keep
      WHERE keep.tenant_id = v_tenant_id AND keep.product_id = v_product_id
      ORDER BY keep.created_at DESC, keep.action_id DESC
      LIMIT 500
    );
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;

