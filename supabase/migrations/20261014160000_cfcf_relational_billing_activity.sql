-- CFCF PRODUCT: Move Cycle billing and Cycle values into relational records.
-- SKELETON: Preserve legacy columns during the compatibility window; drop only after app/RPC cutover.
-- MIX: Owner-checked RPCs own financial writes; payments remain a separate ledger and are never cycle-linked.

ALTER TABLE public.cfcf_cycles
  ADD COLUMN IF NOT EXISTS commission_amount integer,
  ADD CONSTRAINT cfcf_cycles_commission_amount_nonnegative
    CHECK (commission_amount IS NULL OR commission_amount >= 0);

CREATE UNIQUE INDEX IF NOT EXISTS cfcf_cycles_id_fund_tenant_product_uq
  ON public.cfcf_cycles(cycle_id, fund_id, tenant_id, product_id);

CREATE TABLE IF NOT EXISTS public.cfcf_bills (
  bill_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL DEFAULT 'CFCF' CHECK (product_id = 'CFCF'),
  tenant_id text NOT NULL,
  fund_id text NOT NULL,
  cycle_id bigint NOT NULL,
  share_id text NOT NULL,
  amount integer NOT NULL CHECK (amount >= 0),
  bill_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cfcf_bills_one_per_share_cycle UNIQUE (tenant_id, fund_id, cycle_id, share_id),
  CONSTRAINT cfcf_bills_cycle_fk FOREIGN KEY (cycle_id, fund_id, tenant_id, product_id)
    REFERENCES public.cfcf_cycles(cycle_id, fund_id, tenant_id, product_id) ON DELETE CASCADE,
  CONSTRAINT cfcf_bills_share_fk FOREIGN KEY (share_id, fund_id, tenant_id, product_id)
    REFERENCES public.cfcf_shares(share_id, fund_id, tenant_id, product_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS cfcf_bills_fund_cycle_idx
  ON public.cfcf_bills(tenant_id, fund_id, cycle_id);
CREATE INDEX IF NOT EXISTS cfcf_bills_share_idx
  ON public.cfcf_bills(tenant_id, fund_id, share_id);

