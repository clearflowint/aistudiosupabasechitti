-- Dedicated aggregate records for outbound WhatsApp communications.
-- The general job registry remains the execution queue; this table records communication outcomes.
create table if not exists public.n8n_global_whatsapp_communications (
  communication_id bigint generated by default as identity primary key,
  job_id bigint references public.n8n_global_jobs(job_id) on delete set null,
  request_id text not null unique,
  product_id text not null,
  tenant_id text not null,
  source_type text not null,
  communication_type text not null,
  fund_id text,
  status text not null default 'queued'
    check (status in ('queued', 'processing', 'completed', 'failed', 'cancelled')),
  recipient_count integer not null default 0 check (recipient_count >= 0),
  waha_accepted_count integer not null default 0 check (waha_accepted_count >= 0),
  waha_rejected_count integer not null default 0 check (waha_rejected_count >= 0),
  outcome_unknown_count integer not null default 0 check (outcome_unknown_count >= 0),
  result_summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint n8n_global_whatsapp_communications_counts_fit
    check (waha_accepted_count + waha_rejected_count + outcome_unknown_count <= recipient_count)
);

create index if not exists n8n_global_whatsapp_communications_tenant_recent_idx
  on public.n8n_global_whatsapp_communications (product_id, tenant_id, updated_at desc);

create index if not exists n8n_global_whatsapp_communications_job_id_idx
  on public.n8n_global_whatsapp_communications (job_id);

alter table public.n8n_global_whatsapp_communications enable row level security;

-- n8n owns writes. Do not expose this table directly to browser roles until
-- a verified tenant-access policy / safe manager read path is added.
revoke all on table public.n8n_global_whatsapp_communications from anon, authenticated;
grant select, insert, update, delete on table public.n8n_global_whatsapp_communications to service_role;
grant usage, select on sequence public.n8n_global_whatsapp_communications_communication_id_seq to service_role;

comment on table public.n8n_global_whatsapp_communications is
  'Aggregate outcome records for outbound WhatsApp communications. WAHA acceptance is not recipient delivery confirmation.';
comment on column public.n8n_global_whatsapp_communications.waha_accepted_count is
  'Number of send requests accepted by the WAHA server; not a claim of recipient delivery.';
comment on column public.n8n_global_whatsapp_communications.outcome_unknown_count is
  'Number of recipients for which the send outcome could not be determined; do not automatically resend.';



-- Managers may read aggregate communication rows for their own active CFCF tenant.
-- No direct browser writes; n8n service_role owns the communication lifecycle.
create policy n8n_global_whatsapp_communications_manager_read
  on public.n8n_global_whatsapp_communications
  for select
  to authenticated
  using (
    product_id = 'CFCF'
    and public.is_active_tenant_owner(product_id, tenant_id)
  );

grant select on table public.n8n_global_whatsapp_communications to authenticated;
