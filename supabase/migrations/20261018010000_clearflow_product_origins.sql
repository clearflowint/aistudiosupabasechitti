-- Shared ClearFlow push architecture: trusted product origins, independent of product IDs.
-- Origins contain scheme + host only (no path, query, or fragment).
CREATE TABLE IF NOT EXISTS public.clearflow_product_origins (
  origin_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL REFERENCES public.products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  origin text NOT NULL,
  origin_status text NOT NULL DEFAULT 'active'
    CHECK (origin_status IN ('active', 'migration', 'retired')),
  push_enabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT clearflow_product_origins_origin_format
    CHECK (
      origin = lower(origin)
      AND origin ~ '^https://[^/]+$'
      AND position('?' in origin) = 0
      AND position('#' in origin) = 0
    ),
  CONSTRAINT clearflow_product_origins_product_origin_unique UNIQUE (product_id, origin)
);

COMMENT ON TABLE public.clearflow_product_origins IS
  'Server-managed allowlist of approved website origins per permanent ClearFlow product ID. Never use an origin as product identity.';
COMMENT ON COLUMN public.clearflow_product_origins.origin_status IS
  'active = current approved origin; migration = approved overlap during domain migration; retired = no new registrations.';
COMMENT ON COLUMN public.clearflow_product_origins.push_enabled IS
  'Server-side feature gate. Defaults false until push registration and delivery have been deployed and tested.';

ALTER TABLE public.clearflow_product_origins ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.clearflow_product_origins FROM anon, authenticated;
GRANT ALL ON TABLE public.clearflow_product_origins TO service_role;

